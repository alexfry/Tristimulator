#!/bin/bash
# fix_linker_error.sh
# Quick fix for the missing OpenImageIO_Util linker error

set -e

echo "🔧 Fixing Linker Error - Missing OpenImageIO_Util"
echo "=================================================="
echo ""

# Run the add script
chmod +x add_openimageio_util.sh
./add_openimageio_util.sh

echo ""
echo "=================================================="
echo "✅ Library added to Dylibs folder"
echo "=================================================="
echo ""
echo "NOW DO THIS IN XCODE:"
echo "===================="
echo ""
echo "Option A - Quick Method (Recommended):"
echo "--------------------------------------"
echo "1. Build Settings → Search 'Other Linker Flags'"
echo ""
echo "2. Find the current value (probably has):"
echo "   -lOpenImageIO"
echo "   -lOpenColorIO"
echo ""
echo "3. ADD this line:"
echo "   -lOpenImageIO_Util"
echo ""
echo "   Final result should be:"
echo "   -lOpenImageIO"
echo "   -lOpenImageIO_Util"
echo "   -lOpenColorIO"
echo ""
echo "4. Build Phases → Copy Dylibs"
echo "   • Click '+' to add files"
echo "   • Select: Dylibs/libOpenImageIO_Util.dylib (or .3.1.dylib)"
echo "   • Make sure 'Code Sign On Copy' is checked"
echo ""
echo "5. Clean and rebuild:"
echo "   ⌘⇧K then ⌘B"
echo ""
echo ""
echo "Option B - Let Xcode Auto-Link (Alternative):"
echo "---------------------------------------------"
echo "1. Build Phases → Link Binary With Libraries"
echo "   • Click '+'"
echo "   • Click 'Add Other...'"
echo "   • Navigate to: Dylibs/libOpenImageIO_Util.dylib"
echo "   • Add it"
echo ""
echo "2. Make sure it's ALSO in Copy Dylibs phase"
echo ""
echo "3. Clean and rebuild"
echo ""
echo ""
echo "Why This Happened:"
echo "------------------"
echo "OpenImageIO split into two libraries:"
echo "  • libOpenImageIO.dylib - Main image I/O functions"
echo "  • libOpenImageIO_Util.dylib - Utility classes (ParamValue, etc.)"
echo ""
echo "Your code uses ParamValue, which is in _Util library."
echo "The dependency scanner missed it because it's not"
echo "directly linked by libOpenImageIO.dylib."
echo ""
